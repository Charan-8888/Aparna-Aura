/**
 * Returns the hero configuration for a given category slug or builds a fallback
 * for existing categories returned by the backend.
 */
export const getCategoryHeroConfig = (slug, categoryObj) => {
  const normalizedSlug = (slug || '').toLowerCase().trim();

  if (CATEGORY_HERO_CONFIG[normalizedSlug]) {
    return {
      ...CATEGORY_HERO_CONFIG[normalizedSlug],
      isDedicatedHero: true,
    };
  }

  // Fallback configuration for other genuine categories from Django API
  const catName = categoryObj?.name || (normalizedSlug ? normalizedSlug.replace(/-/g, ' ') : 'Jewellery');
  const catDesc = categoryObj?.description || `Explore our handcrafted ${catName.toLowerCase()} collection.`;
  const catImage = (categoryObj?.image && String(categoryObj.image).startsWith('http'))
    ? categoryObj.image
    : 'https://images.unsplash.com/photo-1515562141589-67f0d6ce4819?w=1600&h=600&fit=crop';

  return {
    image: catImage,
    imageFallback: catImage,
    mobileImage: catImage,
    eyebrow: 'APARNA AURA COLLECTION',
    title: catName,
    description: catDesc,
    cta: `Explore ${catName}`,
    desktopPosition: 'center right',
    mobilePosition: 'center center',
    overlay: 'linear-gradient(90deg, rgba(25, 12, 21, 0.90) 0%, rgba(25, 12, 21, 0.65) 38%, rgba(25, 12, 21, 0.20) 68%, rgba(25, 12, 21, 0.03) 100%)',
    mobileOverlay: 'linear-gradient(180deg, rgba(25, 12, 21, 0.85) 0%, rgba(25, 12, 21, 0.60) 60%, rgba(25, 12, 21, 0.20) 100%)',
    isDedicatedHero: false,
  };
};
